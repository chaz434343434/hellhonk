GLYPHS = {}
for ch, art in _G.items():
    rows = art.split(" ")
    w = len(rows[0])
    assert all(len(r) == w for r in rows), ch
    rows += ["." * w] * (ROWS - len(rows))
    GLYPHS[ch] = [(x, y) for y, r in enumerate(rows) for x, c in enumerate(r) if c == "#"], w


def glyph(ch):
    return GLYPHS.get(ch) or GLYPHS["?"]


def text_width(text, unit=1):
    """Width in screen pixels of `text` drawn at `unit` pixels per font pixel."""
    if not text:
        return 0
    return (sum(glyph(c)[1] for c in text) + SPACING * (len(text) - 1)) * unit


class PixelFont:
    def __init__(self):
        self.cache = {}

    def render(self, text, color, unit, shadow=None):
        """Surface with the text; `shadow` colour adds a 1-font-pixel drop shadow (down-right).
        From unit 3 up, strokes get a little heavier (still whole pixels) for a chunkier look."""
        key = (text, color, unit, shadow)
        surf = self.cache.get(key)
        if surf is not None:
            return surf
        bold = unit // 3
        pad = (unit if shadow else 0) + bold
        surf = pygame.Surface((max(1, text_width(text, unit) + pad), ROWS * unit + pad), pygame.SRCALPHA)
        for col, off in ((shadow, unit), (color, 0)) if shadow else ((color, 0),):
            x = 0
            for c in text:
                pts, w = glyph(c)
                for gx, gy in pts:
                    surf.fill(col, (x + gx * unit + off, gy * unit + off, unit + bold, unit))
                x += (w + SPACING) * unit
        if len(self.cache) > 600:
            self.cache.clear()
        self.cache[key] = surf
        return surf
